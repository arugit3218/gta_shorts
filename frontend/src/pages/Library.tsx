import { useRef, useState } from "react";
import { api, media } from "../api";
import { Icon } from "../components/Icon";
import { Alert, Spinner, attempt, useDialogs, useToast } from "../components/ui";
import { usePoll } from "../hooks";
import type { LibraryInfo } from "../types";

const MOOD_DESC: Record<string, string> = {
  energetic: "Default for most clips: upbeat, keeps the pace up.",
  calm: "Used for advice and educational clips.",
  dramatic: "Used for emotional moments and stories.",
};
const SFX_DESC: Record<string, string> = {
  pop: "When the hook title appears",
  whoosh: "On hard camera cuts",
  ding: "On the first number or money amount",
  hit: "On an emphatic line (“but the truth is…”)",
  riser: "Builds into the payoff of longer clips",
};

export default function LibraryPage() {
  const q = usePoll(api.library, []);
  const lib = q.data;
  return (
    <div className="stack lg" style={{ maxWidth: 980 }}>
      <div className="page-head">
        <div>
          <h1>Library</h1>
          <p className="sub">Background music and sound effects used when finishing clips. Everything stays on this Mac.</p>
        </div>
      </div>
      <Alert kind="info">
        Only add music you own or have a licence for. Copyrighted tracks can get Content ID claims on YouTube. Music campaigns usually require the official in-app sound instead, so music and effects are switched off automatically for campaigns that forbid them.
      </Alert>
      {!lib ? (
        <div className="skeleton" style={{ height: 240 }} />
      ) : (
        <>
          <section className="card">
            <div className="card-head">
              <h2>Background music</h2>
              <span className="small muted">
                {Object.values(lib.music).reduce((a, l) => a + l.length, 0)} track(s) · picked per clip by mood, with a different start point each time
              </span>
            </div>
            <div className="card-body stack lg">
              {lib.moods.map((m) => (
                <MoodRow key={m} mood={m} lib={lib} onChange={q.setData} />
              ))}
            </div>
          </section>
          <section className="card">
            <div className="card-head">
              <h2>Sound effects</h2>
              <span className="small muted">Built-in effects are generated by ClipStudio. Add your own to replace them.</span>
            </div>
            <div className="card-body stack">
              {lib.sfx_types.map((k) => (
                <SfxRow key={k} kind={k} lib={lib} onChange={q.setData} />
              ))}
            </div>
          </section>
          <p className="tiny muted mono">{lib.path}</p>
        </>
      )}
    </div>
  );
}

function MoodRow({ mood, lib, onChange }: { mood: string; lib: LibraryInfo; onChange: (l: LibraryInfo) => void }) {
  const toast = useToast();
  const { confirm } = useDialogs();
  const input = useRef<HTMLInputElement>(null);
  const [busy, setBusy] = useState(false);
  const tracks = lib.music[mood] ?? [];
  const add = async (files: File[]) => {
    setBusy(true);
    try {
      let last: LibraryInfo | null = null;
      for (const f of Array.from(files)) last = await api.addMusic(mood, f);
      if (last) onChange(last);
      toast(`${files.length} track(s) added to ${mood}`);
    } catch (e) {
      toast((e as Error).message, "error");
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="stack sm">
      <div className="row between">
        <div className="stack sm" style={{ gap: 2 }}>
          <strong style={{ textTransform: "capitalize" }}>{mood}</strong>
          <span className="small muted">{MOOD_DESC[mood]}</span>
        </div>
        <button className="btn sm" onClick={() => input.current?.click()} disabled={busy}>
          {busy ? <Spinner /> : <Icon name="upload" />} Add tracks
        </button>
        <input ref={input} type="file" accept="audio/*" multiple hidden onChange={(e) => {
            const fs = e.target.files ? Array.from(e.target.files) : [];
            e.target.value = "";
            if (fs.length) add(fs);
          }} />
      </div>
      {tracks.length === 0 ? (
        <span className="small muted">No tracks yet.</span>
      ) : (
        tracks.map((t) => (
          <div className="list-row" key={t.name}>
            <Icon name="music" />
            <span className="ellipsis" style={{ flex: 1 }}>{t.name}</span>
            <span className="tiny muted">{t.mb} MB</span>
            <audio src={media.music(mood, t.name)} controls preload="none" style={{ height: 30, width: 180 }} />
            <button
              className="btn sm icon danger"
              aria-label="Delete track"
              onClick={async () => (await confirm({ title: `Delete “${t.name}”?`, body: "The file is removed from your music library.", confirm: "Delete", danger: true })) && attempt(toast, async () => onChange(await api.deleteMusic(mood, t.name)))}
            >
              <Icon name="trash" />
            </button>
          </div>
        ))
      )}
    </div>
  );
}

function SfxRow({ kind, lib, onChange }: { kind: string; lib: LibraryInfo; onChange: (l: LibraryInfo) => void }) {
  const toast = useToast();
  const { confirm } = useDialogs();
  const input = useRef<HTMLInputElement>(null);
  const files = lib.sfx[kind] ?? [];
  return (
    <div className="list-row" style={{ alignItems: "flex-start" }}>
      <div className="stack sm" style={{ flex: 1, gap: 2 }}>
        <strong style={{ textTransform: "capitalize" }}>{kind}</strong>
        <span className="small muted">{SFX_DESC[kind]}</span>
        {files.map((f) => (
          <span key={f.name} className="row small">
            <Icon name="music" size={12} /> {f.name}
            <button className="btn ghost sm icon" aria-label="Remove" onClick={async () => (await confirm({ title: `Remove “${f.name}”?`, confirm: "Remove", danger: true })) && attempt(toast, async () => onChange(await api.deleteSfx(kind, f.name)))}>
              <Icon name="x" size={12} />
            </button>
          </span>
        ))}
      </div>
      <audio key={files.length} src={media.sfx(kind) + `?n=${files.length}`} controls preload="none" style={{ height: 30, width: 160 }} />
      <button className="btn sm" onClick={() => input.current?.click()}>
        <Icon name="upload" /> {files.length ? "Add another" : "Replace"}
      </button>
      <input
        ref={input}
        type="file"
        accept="audio/*"
        hidden
        onChange={async (e) => {
          const f = e.target.files?.[0];
          e.target.value = "";
          if (!f) return;
          try {
            onChange(await api.addSfx(kind, f));
            toast("Sound effect added");
          } catch (err) {
            toast((err as Error).message, "error");
          }
        }}
      />
    </div>
  );
}
